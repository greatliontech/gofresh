func TestTransitionOwnershipAndCancellation(t *testing.T) {
	im, cut := transitionFixture(t, entryPrefix)
	p, err := ProposeTransition(t.Context(), im, cut, TransitionLimits{})
	if err != nil {
		t.Fatal(err)
	}
	count := &imageCallbackContext{Context: t.Context()}
	c, err := CheckTransition(count, im, transitionFace(), p, TransitionLimits{})
	if err != nil {
		t.Fatal(err)
	}
	baseline, _ := c.Bound()
	// Every callback, including final publication, may replace all input owners.
	for at := 1; at <= count.calls; at++ {
		supplied := *im
		face := transitionFace()
		proposal := p
		proposal.Nodes = append([]Node(nil), p.Nodes...)
		for j := range proposal.Nodes {
			proposal.Nodes[j].Successors = append([]uint64(nil), proposal.Nodes[j].Successors...)
		}
		ctx := &imageCallbackContext{Context: t.Context(), onErr: func(n int) {
			if n == at {
				supplied = Image{}
				face.Regions[0] = RelativeRegion{}
				face.Words[0] = 100
				proposal.Nodes[0].PC = 0
				proposal.Nodes[0].Successors[0] = 0
			}
		}}
		got, err := CheckTransition(ctx, &supplied, face, proposal, TransitionLimits{})
		if err != nil {
			t.Fatalf("owner callback %d: %v", at, err)
		}
		b, _ := got.Bound()
		if !sameImage(got.checked.image, im) || b.ImageDigest != baseline.ImageDigest || !reflect.DeepEqual(b.Accesses, baseline.Accesses) || !reflect.DeepEqual(b.Interface, baseline.Interface) {
			t.Fatal("input mutation crossed owned boundary", at)
		}
		cancelCtx, cancel := context.WithCancel(t.Context())
		stop := &imageCallbackContext{Context: cancelCtx, onErr: func(n int) {
			if n == at {
				cancel()
			}
		}}
		got, err = CheckTransition(stop, im, transitionFace(), p, TransitionLimits{})
		cancel()
		if !errors.Is(err, context.Canceled) || got.checked != nil {
			t.Fatalf("cancellation %d returned %v / %v", at, got, err)
		}
	}
	// Mutation of a projection has no route back into opaque evidence.
	b, _ := c.Bound()
	b.Interface.Regions[0] = RelativeRegion{}
	b.Interface.Words[0] = 99
	b.InitialMemory[0].Value = br.Term{}
	b.Memory[0].Pointer = OriginPointer{}
	b.Words[0].Value = br.Term{}
	b.Accesses[0].Bytes = RelativeSpan{}
	b.Instructions[0] = Span{}
	b.Boundary.Bytes[0] = 0
	b.ExcludedOrigins[0] = Span{}
	again, _ := c.Bound()
	if !reflect.DeepEqual(again, baseline) {
		t.Fatal("projection mutation changed evidence")
	}
	// Discovery also owns the format entry before the first callback.
	supplied := *im
	ctx := &imageCallbackContext{Context: t.Context(), onErr: func(int) { supplied = Image{} }}
	q, err := ProposeTransition(ctx, &supplied, cut, TransitionLimits{})
	if err != nil || !reflect.DeepEqual(p, q) {
		t.Fatal("proposal ownership", q, err)
	}
}

func TestTransitionBudgetsAndEntryPremises(t *testing.T) {
	im, cut := transitionFixture(t, entryPrefix)
	p, err := ProposeTransition(t.Context(), im, cut, TransitionLimits{})
	if err != nil {
		t.Fatal(err)
	}
	for _, l := range []TransitionLimits{
		{RelationLimits: RelationLimits{Instructions: 2}},
		{RelationLimits: RelationLimits{Nodes: 8}},
		{RelationLimits: RelationLimits{Work: 3}},
		{RelationLimits: RelationLimits{Depth: 1}},
		{Regions: 1}, {Bytes: 8}, {Bytes: -1},
	} {
		c, err := CheckTransition(t.Context(), im, transitionFace(), p, l)
		transitionRefused(t, c, err)
	}
	c, err := CheckTransition(nil, im, transitionFace(), p, TransitionLimits{})
	transitionRefused(t, c, err)
	for j := 0; j < 7; j++ {
		f := transitionFace()
		c := &f.Conditions
		fields := []*bool{&c.InstructionMapping, &c.EntryState, &c.IsolatedExecution, &c.MemoryMapping, &c.NoHiddenAliases, &c.UnalignedAccess}
		if j == 6 {
			c.Machine = "other"
		} else {
			*fields[j] = false
		}
		proof, err := CheckTransition(t.Context(), im, f, p, TransitionLimits{})
		transitionRefused(t, proof, err)
	}
	// The only initial scalar word is generated by the checker. Removing its
	// grouping leaves arbitrary bytes, never imports the desired output as fact.
	f := transitionFace()
	f.Words = nil
	c, err = CheckTransition(t.Context(), im, f, p, TransitionLimits{})
	if err != nil {
		t.Fatal(err)
	}
	b, _ := c.Bound()
	if len(b.Words) != 0 || b.Registers[RAX].Value.Sort().Width() != 64 {
		t.Fatal("invented initial word")
	}
	// The request's shape has no term-valued or output-state premise.
	var check func(reflect.Type)
	check = func(typ reflect.Type) {
		if typ == reflect.TypeFor[br.Term]() || typ == reflect.TypeFor[TransitionValue]() {
			t.Fatal("caller can supply symbolic output premise", typ)
		}
		if typ.Kind() == reflect.Struct {
			for j := 0; j < typ.NumField(); j++ {
				check(typ.Field(j).Type)
			}
		}
		if typ.Kind() == reflect.Slice || typ.Kind() == reflect.Array {
			check(typ.Elem())
		}
	}
	check(reflect.TypeFor[TransitionInterface]())
}
